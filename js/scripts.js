// NOTE: The live venue map is a keyless Google Maps <iframe> embed in index.html, so this
// function is no longer wired up. Kept for reference if you ever switch back to the JS API
// (you'd re-add the maps.googleapis.com script tag with callback=initMap and a real key).
function initMap() {
    var location = {lat: 42.9659, lng: -85.6709}; // Grand Rapids Art Museum
    var map = new google.maps.Map(document.getElementById('map-canvas'), {
        zoom: 15,
        center: location,
        scrollwheel: false
    });

    var marker = new google.maps.Marker({
        position: location,
        map: map
    });
}

